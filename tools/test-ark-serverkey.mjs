import puppeteer from 'puppeteer-core';
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await puppeteer.launch({ executablePath: EDGE, headless: 'new', args: ['--no-sandbox','--disable-gpu','--lang=zh-CN'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs=[]; page.on('pageerror', e=>errs.push(e.message)); page.on('console', m=>{ if(m.type()==='error') errs.push(m.text()); });
await page.goto('http://localhost:5180/', { waitUntil: 'networkidle0' });
await page.evaluate(()=>{ localStorage.clear(); localStorage.setItem('farm_tutorial_done','1'); document.getElementById('tutorial').classList.remove('show'); localStorage.setItem('fanmian_ai_v1', JSON.stringify({provider:'ark',key:'',model:'deepseek-v4-1-flash-261017',base:'https://ark.cn-beijing.volces.com/api/v3',auto:false,enabled:true})); });
await page.reload({waitUntil:'networkidle0'});
await new Promise(r=>setTimeout(r,700));
const out = await page.evaluate(async ()=>{ const g=window.__game; const r=await g.triggerAITalk(); return {ok:r.ok, msg:r.msg, story:g.sim.story.slice(-1), bond:g.sim.bond}; });
await new Promise(r=>setTimeout(r,400));
await page.screenshot({ path: 'shots/233-ark-serverkey.png' });
console.log(JSON.stringify({out,errs},null,1));
await browser.close();
