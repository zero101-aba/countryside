import puppeteer from 'puppeteer-core';
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await puppeteer.launch({ executablePath: EDGE, headless: 'new', args: ['--no-sandbox','--disable-gpu','--lang=zh-CN'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs=[]; page.on('pageerror', e=>errs.push(e.message));
await page.goto('http://localhost:5180/', { waitUntil: 'networkidle0' });
await page.evaluate(()=>{ localStorage.clear(); localStorage.setItem('farm_tutorial_done','1'); document.getElementById('tutorial').classList.remove('show'); });
await new Promise(r=>setTimeout(r,600));
await page.evaluate(()=>{ const g=window.__game; g.sim.absHours=10; g.sim.selected=null; g.follow=null; g.renderer.snapTo(27,36.5); });
await new Promise(r=>setTimeout(r,600));
await page.screenshot({ path: 'shots/160-fishing-village.png' });
await page.evaluate(()=>{ window.__game.renderer.snapTo(12,37); });
await new Promise(r=>setTimeout(r,500));
await page.screenshot({ path: 'shots/162-ahai-house.png' });
console.log(JSON.stringify({errs}));
await browser.close();
