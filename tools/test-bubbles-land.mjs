import puppeteer from 'puppeteer-core';
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await puppeteer.launch({ executablePath: EDGE, headless: 'new', args: ['--no-sandbox','--disable-gpu','--lang=zh-CN'] });
const page = await browser.newPage();
await page.setViewport({ width: 844, height: 390, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs=[]; page.on('pageerror', e=>errs.push(e.message));
await page.goto('http://localhost:5180/', { waitUntil: 'networkidle0' });
await page.evaluate(()=>{ localStorage.clear(); localStorage.setItem('farm_tutorial_done','1'); document.getElementById('tutorial').classList.remove('show'); });
await new Promise(r=>setTimeout(r,700));
await page.evaluate(()=>{
  const g=window.__game, s=g.sim;
  g.setSpeed(0);
  const vs=s.villagers.slice(0,4);
  vs.forEach((v,i)=>{ v.x=13+i*2.2; v.y=13.2; v.path=null; v.task=null; v.state='auto'; v.dir='down'; });
  vs[0].say('今天天气真好。','😊',30);
  vs[1].say('东家，我饿了。','🍞',30);
  vs[2].say('这活儿真累人。','😪',30);
  vs[3].say('河边的鱼真多。','🎣',30);
  g.selectVillager(vs[0]); g.ui.closeSheet();
  g.renderer.snapTo(16.5,12.6); g.follow=null;
});
await new Promise(r=>setTimeout(r,800));
await page.screenshot({ path: 'shots/121-landscape-bubbles.png' });
console.log(JSON.stringify({bubbles: await page.evaluate(()=>document.querySelectorAll('.w-bubble:not(.hidden)').length), errs}));
await browser.close();
