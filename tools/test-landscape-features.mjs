import puppeteer from 'puppeteer-core';
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await puppeteer.launch({ executablePath: EDGE, headless: 'new', args: ['--no-sandbox','--disable-gpu','--lang=zh-CN'] });
const page = await browser.newPage();
await page.setViewport({ width: 844, height: 390, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs=[]; page.on('pageerror', e=>errs.push(e.message)); page.on('console', m=>{ if(m.type()==='error') errs.push(m.text()); });
await page.goto('http://localhost:5180/', { waitUntil: 'networkidle0' });
await page.evaluate(()=>{ localStorage.clear(); localStorage.setItem('farm_tutorial_done','1'); document.getElementById('tutorial').classList.remove('show'); });
await new Promise(r=>setTimeout(r,700));
const layout = await page.evaluate(()=>{
  const btns=document.querySelectorAll('#toolbar button');
  const stage=document.getElementById('stage').getBoundingClientRect();
  return { buttons: btns.length, labels:[...btns].map(b=>b.textContent.trim()), stage:[Math.round(stage.width),Math.round(stage.height)] };
});
await page.screenshot({ path: 'shots/170-landscape-features.png' });
await page.evaluate(()=>window.__game.ui.openQuests());
await new Promise(r=>setTimeout(r,500));
await page.screenshot({ path: 'shots/171-landscape-quests.png' });
const panel = await page.evaluate(()=>{ const r=document.querySelector('.sheet-panel').getBoundingClientRect(); return [Math.round(r.x),Math.round(r.width),Math.round(r.height)]; });
console.log(JSON.stringify({layout, panel, errs}));
await browser.close();
