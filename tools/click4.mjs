import puppeteer from 'puppeteer-core';
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await puppeteer.launch({ executablePath: EDGE, headless: 'new', args: ['--no-sandbox','--disable-gpu','--lang=zh-CN'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs=[]; page.on('pageerror', e=>errs.push(e.message));
await page.goto('http://localhost:5180/', { waitUntil: 'networkidle0' });
await page.evaluate(()=>{ localStorage.clear(); localStorage.setItem('farm_tutorial_done','1'); document.getElementById('tutorial').classList.remove('show'); });
await new Promise(r=>setTimeout(r,500));
await page.evaluate(()=>window.__game.selectVillager(window.__game.sim.villagers[0]));
await new Promise(r=>setTimeout(r,300));
await page.evaluate(()=>document.querySelector('[data-cmd="plow"]').click());
await new Promise(r=>setTimeout(r,1500));
const pt = await page.evaluate(()=>{ const g=window.__game; const r=document.getElementById('game').getBoundingClientRect(); const s=g.renderer.worldToScreen(10.5,13.5); return {x:r.x+s.x,y:r.y+s.y}; });
console.log('click at', JSON.stringify(pt));
await page.mouse.click(pt.x, pt.y);
await new Promise(r=>setTimeout(r,900));
const st = await page.evaluate(()=>{ const g=window.__game; const v=g.sim.villagers[0]; return {mode:g.mode, task:v.task?.type, stage:v.task?.stage, follow:!!g.follow, pos:[+v.x.toFixed(1),+v.y.toFixed(1)]}; });
console.log('after click', JSON.stringify(st), 'errs', errs);
await page.screenshot({ path: 'tools/shots/73-click-work.png' });
await new Promise(r=>setTimeout(r,2500));
const st2 = await page.evaluate(()=>{ const g=window.__game; const v=g.sim.villagers[0]; return {stage:v.task?.stage, progress:+(v.task?.progress||0).toFixed(2), plowed:g.sim.world.plots.filter(p=>p.state==='plowed').length}; });
console.log('later', JSON.stringify(st2));
await page.screenshot({ path: 'tools/shots/74-working.png' });
await browser.close();

